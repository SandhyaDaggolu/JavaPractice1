package com.Operators;

// Shift operators -> << >> >>>

public class ShiftOperators {

	public static void main(String[] args) {
		int a = 93;
		int b = 3;
		
		// Left Shift Operator
		System.out.println(a << b);// 744
		System.out.println(a >> b);// 11
		System.out.println(a >>> b);// 11

	}

}
